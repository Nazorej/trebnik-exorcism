def zone_of(svc, n):
    """Зонные умолчания."""
    if svc == "01":
        if 1 <= n <= 23:
            return "NARR"
        if 100 <= n <= 289:
            return "CHOIR"
        return "PRIEST"
    else:
        if 1 <= n <= 16:
            return "NARR"
        return "PRIEST"


def classify(line, zone, marker):
    """Возвращает (голос, новый_marker, is_rubric)."""
    s = line.strip()
    if not s:
        return None, marker, True
    if zone == "NARR":
        return C, marker, True
    if s in CHOIR_ONE:
        return C, marker, False
    if HEADER_RE.match(s) or TITLE_RE.match(s):
        return C, marker, True
    m = CHOIR_ROLE_RE.search(s)
    if m and m.start() < 55:
        return C, C, True
    if PRIEST_ROLE_RE.search(s) and (PRIEST_VERB_RE.search(s) or s.endswith(":")):
        return C, P, True
    is_starter = any(s.startswith(x) for x in STARTERS)
    if is_starter or (s.endswith(":") and SPEECH_VERB_RE.search(s)):
        # рубрика; в священнических зонах глаголы речи переключают на священника
        if zone == "PRIEST" and PRIEST_VERB_RE.search(s):
            return C, P, True
        return C, marker, True
    return marker, marker, False


