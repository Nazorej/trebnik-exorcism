def build(svc, ops, parts, src):
    lines = open(src, encoding="utf-8").read().split("\n")
    lines = [apply_fixes(l) for l in lines]
    lines = [fix_name(l) for l in lines]
    utter = []  # (line_no, voice, text)
    for i, ln in enumerate(lines, 1):
        if not ln.strip():
            continue
        op = ops.get(i)
        if op:
            kind, payload = op
            if kind == "replace":
                for v, t in payload:
                    utter.append((i, v, t))
            # insert_after обрабатываем после строки
            if kind == "replace" or kind == "delete":
                if kind == "insert_after":
                    pass
            if kind == "insert_after":
                utter.append((i, None, ln))  # сама строка
                for v, t in payload:
                    utter.append((i, v, t))
                continue
            continue
        utter.append((i, None, ln))
    # вторая фаза: классификация строк с голосом None
    marker = P
    out = []  # (part_idx, voice, text, line_no)
    part_bounds = parts
    pi = 0
    for (i, v, t) in utter:
        # часть: pi указывает на часть, содержащую строку i
        while pi + 1 < len(part_bounds) and i > part_bounds[pi][1]:
            pi += 1
        if v is not None:
            # вставленный/заменённый текст: голос уже задан
            out.append((pi, v, t, i))
            continue
        zone = zone_of(svc, i)
        voice, marker, _ = classify(t, zone, marker)
        if voice is None:
            continue
        out.append((pi, voice, t, i))
    return out


