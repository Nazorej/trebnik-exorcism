def tts_clean(text: str) -> str:
    """Финальная зачистка текста перед синтезом:
    - ъ не озвучивается корректно (движок договаривает лишнее) — удаляем;
    - «Ии» в начале слова читается как «Э» (Иисусе → Эсусе) — меняем
      на «Йи» (звучит как правильное «Йиисусе»)."""
    text = text.replace("ъ", "").replace("Ъ", "")
    text = re.sub(r"\bИисус", "Йисус", text)
    text = re.sub(r"\bиисус", "йисус", text)
    return re.sub(r"[ \t]{2,}", " ", text).strip()

