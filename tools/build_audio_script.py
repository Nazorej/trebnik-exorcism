def load_psalms():
    raw = open(f"{BASE}/psalms_raw.txt", encoding="utf-8").read()
    blocks = re.split(r"=== ПСАЛОМ (\d+) ===", raw)
    psalms = {}
    for i in range(1, len(blocks), 2):
        n = int(blocks[i])
        body = blocks[i + 1]
        body = body.split("[надписание]", 1)[-1].strip()
        # внутренние номера стихов: после знака препинания
        body = re.sub(r"(?<=[.,;:?!…])\s+\d{1,3}\s+", " ", body)
