def apply_fixes(line):
    for pat, rep_ in FIXES:
        line = re.sub(pat, rep_, line)
    line = OU_RE.sub(lambda m: ("У" if m.group(0) == "Оу" else "у"), line)
    for stem in SO_FIXES:
        line = line.replace(stem, "со" + stem[2:])
    for stem in STRIP_E:
        line = line.replace(stem, stem[0] + stem[2:])
    line = re.sub(r"\s+", " ", line).strip()
    return line


# ============================================================ 4. ИМЯРЕК → МАКСИМ
# Падеж определяется по контексту перед каждым вхождением:
#   рабу твоему (дат.) → Максиму; о/въ рабе (предл.) → Максиме;
#   въ тебе (зват.) → Максиме; въ рабе Божии (предл.) → Максиме;
#   прочее (род.) → Максима
NAME_CTX = [
    (re.compile(r"рабу твоему,?\s*$"), "Максиму"),
    (re.compile(r"о рабе твоемъ?,?\s*$"), "Максиме"),
    (re.compile(r"въ тебе\s*$"), "Максиме"),
    (re.compile(r"въ рабе Божии\s*$"), "Максиме"),
    (re.compile(r"человека сего,?\s*$"), "Максима"),
]
NAME_TOKEN = "Имярекъ"


def fix_name(line):
    out = []
    i = 0
    while True:
        j = line.find(NAME_TOKEN, i)
        if j < 0:
            out.append(line[i:])
            break
        ctx = line[max(0, j - 30):j]
        repl = "Максима"
        for pat, r in NAME_CTX:
            if pat.search(ctx):
                repl = r
                break
        out.append(line[i:j])
        out.append(repl)
        i = j + len(NAME_TOKEN)
    return "".join(out)


