STRIP_DECO = re.compile(r"[\u0486\u0485\u0484\u0301\u0300\u0308\u033E]")
TITLO_LEFT = re.compile(r"[\u0483\u0487\uA67C\u2DE0-\u2DFF\uA69C\uA69D\u033E]")
TOKEN_RE = re.compile(r"[\w\u0300-\u036F\u0483-\u0489\uA640-\uA69F\u2DE0-\u2DFF\u1C80-\u1C8F]+", re.UNICODE)


def normalize_token(tok, report):
    had_tilde = "\u033E" in tok
    probe = STRIP_DECO.sub("", tok)

    # ̾-слова (оверстрок скрывает ь/о)
    if had_tilde and probe in EXACT_TILDE:
        return EXACT_TILDE[probe]

    # числовой титло? (до паттернов и до срезания конечных титл!)
    n = try_numeral(probe)
    if n is not None:
        return f"«{n}»"

    # основы
    for pat, rep in PATTERNS:
        new = re.sub(pat, rep, probe, flags=re.IGNORECASE)
        if new != probe:
            probe = new

    # точный словарь
    if probe in EXACT:
        return EXACT[probe]

    # срезаем декоративные титлы в конце токена (Словесы҃ → Словесы)
    probe = re.sub(r"[\u0483\u0487\uA67C\u2DE0-\u2DFF]+$", "", probe)

    # остался титло-мусор?
    if TITLO_LEFT.search(probe):
        report.append(tok)
    return probe


def convert_letters(text):
    def repl(m):
        return LETTER_MAP.get(m.group(0), m.group(0))
    return re.sub(r"[ѣѢѡѠѿѾѻѺꙋꙊꙍꙌіІїЇѝѐѵѴѳѲѱѰѯѮєЄѕЅѧѦꙗꙖѭѨѫѪѥꙁꙀᲃᲂјЈ]", repl, text)


NUM_ORD_F = re.compile(r"([Пп]ѣснь|Пѣ́снь|[Пп]еснь),?\s+«(\d+)»")
NUM_ORD_F2 = re.compile(r"(Мл҃тва|Молитва|[Мм]олитва),?\s+«(\d+)»")
NUM_ORD_M = re.compile(r"([Гг]ласъ|[Гг]лас|Гла́съ),?\s+«(\d+)»")
NUM_CARD = re.compile(r"«(\d+)»")


def num_words_line(line):
    line = NUM_ORD_F.sub(lambda m: f"{m.group(1)} {ordinal_word(int(m.group(2)), 'f')}", line)
    line = NUM_ORD_F2.sub(lambda m: f"{m.group(1)} {ordinal_word(int(m.group(2)), 'f')}", line)
    line = NUM_ORD_M.sub(lambda m: f"{m.group(1)} {ordinal_word(int(m.group(2)), 'm')}", line)
    # «N» в конце строки — номер молитвы (жен.): К ... учителем, 7-я
    line = re.sub(r",\s*«(\d+)»\s*$", lambda m: f", {ordinal_word(int(m.group(1)), 'f')}", line)
    # прочие числа — количественные
    line = NUM_CARD.sub(lambda m: cardinal(int(m.group(1))), line)
    return line


def final_cleanup(line):
    line = re.sub(r"\s*\((?:или|и҆ли)[^)]*\)", "", line, flags=re.I)
    line = re.sub(r"\(([^)]*)\)", r"\1", line)
    # символы вне BMP (кресты и пр.)
    line = re.sub(r"[\U00010000-\U0010FFFF]", "", line)
    # падежные окончания голого «Іи҃с» по соседнему слову
    line = re.sub(r"\bИисус (Христа\b)", r"Иисуса \1", line)
    line = re.sub(r"\bИисус (Христе\b)", r"Иисусе \1", line)
    line = re.sub(r"\bИисус (Христомъ?)\b", r"Иисусом \1", line)
    line = re.sub(r"\bИисус (Христу\b)", r"Иисусу \1", line)
    line = re.sub(r"\bИисус (Христови\b)", r"Иисусови \1", line)
    # прочее OCR
    line = re.sub(r"\bсиестъ\b", "си есть", line)
    # унификация смѣренн → смиренн (в тексте оба варианта)
    line = re.sub(r"\bсмеренн", "смиренн", line)
    line = re.sub(r"\bсмерени", "смирени", line)
    # кафулическ → кафолическ
    line = re.sub(r"кафулическ", "кафолическ", line)
    # OCR-имена святых и мелочи
    line = re.sub(r"\bИуанн", "Иоанн", line)
    line = re.sub(r"\bСвм", "Сим", line)
    line = re.sub(r"\bАнтун", "Антон", line)
    line = re.sub(r"окропрением", "окроплением", line)
    line = re.sub(r"\s+", " ", line).strip()
    return line


